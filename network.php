    // 3D tilt on net cards
    document.querySelectorAll('.net-card-main').forEach(card => {
      card.addEventListener('mousemove', e => {
        const r = card.getBoundingClientRect();
        const rx = -(e.clientY - r.top - r.height / 2) / r.height * 10;
        const ry = (e.clientX - r.left - r.width / 2) / r.width * 10;
        card.style.transform = `translateY(-10px) rotateX(${rx}deg) rotateY(${ry}deg)`;
      });
      card.addEventListener('mouseleave', () => card.style.transform = '');
    });
